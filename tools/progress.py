#!/usr/bin/env python3
"""Measure how far the rewrite has come and write it into ROADMAP.md.

    tools/progress.py            print the progress block
    tools/progress.py --write    replace the block in ROADMAP.md

Everything in the block is counted from the repository, so anyone can
rerun it:

- Roadmap items per phase (P0-P9 only, nested items included): done `[x]`,
  in progress `[~]`, not started `[ ]`.
- Game functions the address database records (data/addresses/*.toml) and
  how many of those say we reimplemented them, counting only Maxis code
  (entries in the third-party and compiler ranges below are left out of
  the share). This undercounts what is ours: functions swapped through
  vtable slots often have no entry.
- Replacement toggles registered in src/core, by area (diagnostics and
  determinism toggles are tooling and left out).

Of the exe's 34,557 functions, 27,473 are Maxis code (game and GZ
framework); the rest are compiler-generated stubs and third-party
libraries the project keeps as they are (docs/uncharted-code.md, "The
true total"). The share is of the Maxis code.
The per-area estimates under the block in ROADMAP.md are a judgment, kept
by hand; the coverage meter with everything set to ours would give the
exact share of original code still running.

Standard library only (Python 3.11+ for tomllib).
"""
import argparse
import datetime
import re
import sys
import tomllib
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ROADMAP = ROOT / "ROADMAP.md"
BEGIN = "<!-- progress:begin (generated by tools/progress.py; do not edit) -->"
END = "<!-- progress:end -->"
GAME_FUNCTIONS = 27473
# Third-party libraries and the compiler's tail (docs/uncharted-code.md).
# Thunks and static initializers elsewhere are not range-shaped; the few
# entries for them still count.
NOT_MAXIS = [
    (0x00864B60, 0x008747D4),  # AEMS
    (0x008B96F0, 0x008BC430),  # Lua 5.0 runtime, before the game's thread table
    (0x008BD8AD, 0x008BE930),  # Lua, between the thread table and the tag library
    (0x008BF268, 0x008D01F0),  # Lua, after the tag library
    (0x009DC730, 0x00A64110),  # STLport, C runtime, Gimex and its codecs
    (0x00A66742, 0x00A7FA24),  # MPEG decoder, C runtime tail, compiler's tail
]
OURS = re.compile(r"[Rr]eimplement|replaceable|\bours\b|\bOurs\b|replaced by|(simulators|renderer)\.[a-z]")
TOGGLE = re.compile(r'"((?:simulators|renderer|resources|game|ui|framework|region|audio|saves)\.[a-z0-9_.]+)"')


def roadmap_phases(text):
    phases, current = [], None
    for line in text.splitlines():
        heading = re.match(r"## (P\d): (.*)", line)
        if heading:
            current = {"phase": heading[1], "title": heading[2].split(" (")[0], "x": 0, "~": 0, " ": 0}
            phases.append(current)
        elif line.startswith("## "):
            current = None
        elif current:
            item = re.match(r"\s*- \[([ x~])\]", line)
            if item:
                current[item[1]] += 1
    return phases


def address_functions():
    total = ours = 0
    for path in sorted((ROOT / "data" / "addresses").glob("*.toml")):
        for entry in tomllib.loads(path.read_text(encoding="utf-8")).get("entry", []):
            address = entry.get("address", 0)
            if isinstance(address, str):
                address = int(address, 16)
            if entry.get("kind") == "function" and not any(lo <= address < hi for lo, hi in NOT_MAXIS):
                total += 1
                ours += bool(OURS.search(entry.get("source", "")))
    return total, ours


def toggles():
    names = set()
    for path in (ROOT / "src").rglob("*.[ch]*"):
        names.update(TOGGLE.findall(path.read_text(encoding="utf-8", errors="replace")))
    return Counter(name.split(".")[0] for name in names)


def block(text):
    phases = roadmap_phases(text)
    total, ours = address_functions()
    areas = toggles()
    done = sum(p["x"] for p in phases)
    doing = sum(p["~"] for p in phases)
    items = sum(p["x"] + p["~"] + p[" "] for p in phases)
    lines = [
        BEGIN,
        f"Measured {datetime.date.today().isoformat()}:",
        "",
        f"- Roadmap (P0-P9): {done} of {items} items done, {doing} in progress.",
        f"- Address database: {total} Maxis functions recorded, {ours} of them reimplemented "
        f"({ours / GAME_FUNCTIONS:.1%} of the game's {GAME_FUNCTIONS:,} functions of Maxis code; "
        "a lower bound, vtable swaps are not all recorded).",
        "- Replacement toggles: " + ", ".join(f"{n} {a}" for a, n in sorted(areas.items(), key=lambda kv: -kv[1])) + ".",
        "",
        "| Phase | Done | In progress | Not started |",
        "|---|---|---|---|",
    ]
    lines += [f"| {p['phase']} {p['title']} | {p['x']} | {p['~']} | {p[' ']} |" for p in phases]
    lines.append(END)
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--write", action="store_true", help="replace the block in ROADMAP.md")
    args = parser.parse_args()
    text = ROADMAP.read_text(encoding="utf-8")
    new = block(text)
    if not args.write:
        print(new)
        return 0
    start, end = text.find(BEGIN), text.find(END)
    if start < 0 or end < 0:
        sys.exit(f"{ROADMAP}: progress markers not found")
    ROADMAP.write_text(text[:start] + new + text[end + len(END):], encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
