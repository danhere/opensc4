#!/usr/bin/env python3
"""Measure how far the rewrite has come and write it into ROADMAP.md.

    tools/progress.py            print the progress block
    tools/progress.py --write    replace the block in ROADMAP.md

Everything in the block is counted from the repository, so anyone can
rerun it:

- Roadmap items per phase (P0-P9 only, nested items included): done `[x]`,
  in progress `[~]`, not started `[ ]`.
- Game functions the address database records (data/addresses/*.toml) and
  how many of those say we reimplemented them. This undercounts what is
  ours: functions swapped through vtable slots often have no entry.
- Replacement toggles registered in src/core, by area (diagnostics and
  determinism toggles are tooling and left out).

The game has 34,556 functions (docs/dev-environment.md, "Coverage meter").
The per-area estimates under the block in ROADMAP.md are a judgment, kept
by hand; the coverage meter with everything set to ours would give the
exact share of original code still running.

Standard library only (Python 3.11+ for tomllib).
"""
import argparse
import datetime
import re
import sys
import tomllib
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ROADMAP = ROOT / "ROADMAP.md"
BEGIN = "<!-- progress:begin (generated by tools/progress.py; do not edit) -->"
END = "<!-- progress:end -->"
GAME_FUNCTIONS = 34556
OURS = re.compile(r"[Rr]eimplement|replaceable|\bours\b|\bOurs\b|replaced by|(simulators|renderer)\.[a-z]")
TOGGLE = re.compile(r'"((?:simulators|renderer|resources|game|ui|framework)\.[a-z0-9_.]+)"')


def roadmap_phases(text):
    phases, current = [], None
    for line in text.splitlines():
        heading = re.match(r"## (P\d): (.*)", line)
        if heading:
            current = {"phase": heading[1], "title": heading[2].split(" (")[0], "x": 0, "~": 0, " ": 0}
            phases.append(current)
        elif line.startswith("## "):
            current = None
        elif current:
            item = re.match(r"\s*- \[([ x~])\]", line)
            if item:
                current[item[1]] += 1
    return phases


def address_functions():
    total = ours = 0
    for path in sorted((ROOT / "data" / "addresses").glob("*.toml")):
        for entry in tomllib.loads(path.read_text(encoding="utf-8")).get("entry", []):
            if entry.get("kind") == "function":
                total += 1
                ours += bool(OURS.search(entry.get("source", "")))
    return total, ours


def toggles():
    names = set()
    for path in (ROOT / "src").rglob("*.[ch]*"):
        names.update(TOGGLE.findall(path.read_text(encoding="utf-8", errors="replace")))
    return Counter(name.split(".")[0] for name in names)


def block(text):
    phases = roadmap_phases(text)
    total, ours = address_functions()
    areas = toggles()
    done = sum(p["x"] for p in phases)
    doing = sum(p["~"] for p in phases)
    items = sum(p["x"] + p["~"] + p[" "] for p in phases)
    lines = [
        BEGIN,
        f"Measured {datetime.date.today().isoformat()}:",
        "",
        f"- Roadmap (P0-P9): {done} of {items} items done, {doing} in progress.",
        f"- Address database: {total} game functions recorded, {ours} of them reimplemented "
        f"({ours / GAME_FUNCTIONS:.1%} of the game's {GAME_FUNCTIONS:,}; a lower bound, vtable swaps are not all recorded).",
        "- Replacement toggles: " + ", ".join(f"{n} {a}" for a, n in sorted(areas.items(), key=lambda kv: -kv[1])) + ".",
        "",
        "| Phase | Done | In progress | Not started |",
        "|---|---|---|---|",
    ]
    lines += [f"| {p['phase']} {p['title']} | {p['x']} | {p['~']} | {p[' ']} |" for p in phases]
    lines.append(END)
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--write", action="store_true", help="replace the block in ROADMAP.md")
    args = parser.parse_args()
    text = ROADMAP.read_text(encoding="utf-8")
    new = block(text)
    if not args.write:
        print(new)
        return 0
    start, end = text.find(BEGIN), text.find(END)
    if start < 0 or end < 0:
        sys.exit(f"{ROADMAP}: progress markers not found")
    ROADMAP.write_text(text[:start] + new + text[end + len(END):], encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
